CREATE TABLE public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT,
    sort_order BIGINT NOT NULL
);

CREATE UNIQUE INDEX categories_name_nocase_key
    ON public.categories (lower(name));

CREATE TABLE public.menu_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    category TEXT NOT NULL REFERENCES public.categories(name)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    price DOUBLE PRECISION NOT NULL CHECK (price > 0),
    is_available SMALLINT NOT NULL CHECK (is_available IN (0, 1))
);

CREATE UNIQUE INDEX menu_items_name_nocase_key
    ON public.menu_items (lower(name));

CREATE TABLE public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name TEXT NOT NULL,
    menu_item_id BIGINT NOT NULL REFERENCES public.menu_items(id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    quantity BIGINT NOT NULL CHECK (quantity BETWEEN 1 AND 5),
    note TEXT,
    created_at TEXT NOT NULL
);

ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.menu_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
